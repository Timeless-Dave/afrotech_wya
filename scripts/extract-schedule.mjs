// Usage: node scripts/extract-schedule.mjs <saved schedule.html>
// Reads the AfroTech schedule page, keeps Student/Premiere events inside the
// trip window, writes data/schedule.json, data/rooms.json and SKIPPED.md.
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync(process.argv[2], 'utf8');
const WIN_START = Date.parse('2026-11-02T00:00:00-06:00');
const WIN_END = Date.parse('2026-11-05T12:00:00-06:00');
const KEEP_LEVELS = ['Student', 'Premiere'];

const decode = s => s
  .replace(/<[^>]+>/g, '')
  .replace(/&amp;/g, '&').replace(/&#39;|&#x27;/g, "'").replace(/&quot;/g, '"')
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&nbsp;/g, ' ')
  .replace(/\s+/g, ' ').trim();

// JSON-LD events, used to cross check times: name -> [{start,end,room}]
const ld = new Map();
for (const m of html.matchAll(/<script type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/g)) {
  let j; try { j = JSON.parse(m[1]); } catch { continue; }
  const walk = o => {
    if (Array.isArray(o)) return o.forEach(walk);
    if (o && typeof o === 'object') {
      if (o['@type'] === 'Event' && o.startDate) {
        const k = decode(o.name);
        if (!ld.has(k)) ld.set(k, []);
        ld.get(k).push({ start: Date.parse(o.startDate), end: Date.parse(o.endDate), room: o.location?.name });
      }
      Object.values(o).forEach(walk);
    }
  };
  walk(j);
}

function toEpoch(day, t) {
  const m = t.match(/^(\d{1,2}):(\d{2})\s*(AM|PM)$/i);
  if (!m) return NaN;
  let h = +m[1] % 12; if (m[3].toUpperCase() === 'PM') h += 12;
  return Date.parse(`${day}T${String(h).padStart(2, '0')}:${m[2]}:00-06:00`);
}

const panels = [...html.matchAll(/id="schedule-panel-(\d{4}-\d{2}-\d{2})"/g)].map(m => ({ i: m.index, day: m[1] }));
const kept = [], skipped = [], late = [];
for (const m of html.matchAll(/<article id="session-([0-9a-f-]{36})"[\s\S]*?<\/article>/g)) {
  const card = m[0], id = m[1];
  const day = panels.filter(p => p.i < m.index).pop()?.day;
  const title = decode(card.match(/schedule-card__title[^>]*>([\s\S]*?)<\/h3>/)?.[1] || '');
  const time = decode(card.match(/schedule-card__time[^>]*>([\s\S]*?)<\/p>/)?.[1] || '');
  const ticketsRaw = card.match(/schedule-card__tickets[^>]*>([\s\S]*?)<\/p>/)?.[1];
  const levels = ticketsRaw ? decode(ticketsRaw).replace(/^Ticket Level:\s*/i, '').split(',').map(s => s.trim()).filter(Boolean) : [];
  const tm = time.match(/^(\d{1,2}:\d{2}\s*[AP]M)\s*-\s*(\d{1,2}:\d{2}\s*[AP]M)\s*·\s*(.+)$/i);
  const label = `${day || '?'} | ${time || '?'} | ${title || '?'}`;

  if (!day || !title || !tm) { skipped.push([label, 'missing day, time, room or title']); continue; }
  const start = toEpoch(day, tm[1]), end = toEpoch(day, tm[2]), room = tm[3].trim();
  if (!(end > start)) { skipped.push([label, 'end time not after start']); continue; }
  if (start < WIN_START || start >= Date.parse('2026-11-06T00:00:00-06:00')) continue; // outside trip days
  if (!levels.length) { skipped.push([label, 'no ticket level listed']); continue; }
  if (!levels.some(l => KEEP_LEVELS.includes(l))) continue; // filtered by level, not a data problem
  if (end > WIN_END) { late.push(label); continue; }

  const cross = ld.get(title);
  if (cross && !cross.some(c => c.start === start && c.end === end)) {
    skipped.push([label, 'card time does not match the page event data']); continue;
  }
  kept.push({ id, title, day, start: new Date(start).toISOString(), end: new Date(end).toISOString(), room, levels });
}

kept.sort((a, b) => a.start.localeCompare(b.start) || a.title.localeCompare(b.title));
writeFileSync('data/schedule.json', JSON.stringify(kept));

const rooms = [...new Set(kept.map(e => e.room))].sort();

const md = ['# Skipped events', '', 'Events from https://afrotechconference.com/schedule left out of the tracker.',
  'Kept rule: ticket level includes Student or Premiere, Mon Nov 2 through Thu Nov 5 12:00 PM (Houston time).', '',
  '## Could not verify', '', '| Event | Reason |', '| --- | --- |', ...skipped.map(([l, r]) => `| ${l.replace(/\|/g, '/')} | ${r} |`),
  '', '## Student or Premiere, but ends after Thu 12:00 PM', '', ...late.map(l => `- ${l}`)];
writeFileSync('SKIPPED.md', md.join('\n') + '\n');
console.log(`cards: ${kept.length + skipped.length}+ kept: ${kept.length} skipped: ${skipped.length} rooms: ${rooms.length}`);
console.log(rooms.join('\n'));

const q = s => `'${s.replace(/'/g, "''")}'`;
writeFileSync('supabase/events.sql', '-- Generated by scripts/extract-schedule.mjs. Run after schema.sql.\n' +
  'insert into events (id, title, starts_at, ends_at, room, levels) values\n' +
  kept.map(e => `(${q(e.id)}, ${q(e.title)}, ${q(e.start)}, ${q(e.end)}, ${q(e.room)}, array[${e.levels.map(q).join(', ')}])`).join(',\n') +
  '\non conflict (id) do update set title = excluded.title, starts_at = excluded.starts_at,\n' +
  '  ends_at = excluded.ends_at, room = excluded.room, levels = excluded.levels;\n');
